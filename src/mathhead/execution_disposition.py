def _intent_from_mapping(
    value: object, path: str = "$", *, relation: bool = False
) -> CancellationIntent:
    item = _keys(value, _INTENT_FIELDS, path)
    if (
        item["schema"] != CANCELLATION_INTENT_SCHEMA
        or item["policy_contract_id"] != CONTRACT_ID
        or item["policy_contract_sha256"] != CONTRACT_SHA256
        or item["mathematical_authority"] is not False
    ):
        raise _Invalid(f"{path} contract binding differs")
    result = _make(
        CancellationIntent,
        schema=CANCELLATION_INTENT_SCHEMA,
        intent_id=_identifier(item["intent_id"], f"{path}.intent_id"),
        origin_source=_choice(
            item["origin_source"], {"user", "parent", "supervisor"}, f"{path}.origin_source"
        ),
        reason_code=_choice(
            item["reason_code"],
            {"requested", "superseded", "shutdown", "policy_stop"},
            f"{path}.reason_code",
        ),
        invocation_id=_identifier(item["invocation_id"], f"{path}.invocation_id"),
        invocation_sha256=_digest(item["invocation_sha256"], f"{path}.invocation_sha256"),
        base_parent_budget_sha256=_digest(
            item["base_parent_budget_sha256"], f"{path}.base_parent_budget_sha256"
        ),
        policy_contract_id=CONTRACT_ID,
        policy_contract_sha256=CONTRACT_SHA256,
        intent_sha256=_digest(item["intent_sha256"], f"{path}.intent_sha256"),
        mathematical_authority=False,
    )
    if result.intent_sha256 != _self_hash(_intent_mapping(result), "intent_sha256"):
        raise _Invalid(f"{path}.intent_sha256 identity mismatch")
    del relation
    return result


def parse_cancellation_intent(data: bytes) -> CancellationIntent:
    try:
        return _intent_from_mapping(_parse(data))
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except _Exhausted as exc:
        _fail("limit", "$", str(exc))
    except Exception as exc:
        if isinstance(exc, ExecutionDispositionValidationError):
            raise
        _fail("identity", "$", str(exc))


def validate_cancellation_intent(value: CancellationIntent) -> None:
    if type(value) is not CancellationIntent:
        _fail("type", "$", "expected exact CancellationIntent")
    try:
        if _intent_from_mapping(_intent_mapping(value)) != value:
            raise _Invalid("in-memory cancellation intent differs")
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception as exc:
        if isinstance(exc, ExecutionDispositionValidationError):
            raise
        _fail("identity", "$", str(exc))


def cancellation_intent_bytes(value: CancellationIntent) -> bytes:
    validate_cancellation_intent(value)
    return _canonical(_intent_mapping(value))



def _quantity(value: object, path: str, maximum: int = INTEGER_MAXIMUM) -> int:
    if type(value) is not int or not 0 <= value <= maximum:
        raise _Invalid(f"{path} must be an exact bounded integer")
    return value


def _choice(value: object, choices: set[str] | tuple[str, ...], path: str) -> str:
    if type(value) is not str or value not in choices:
        raise _Invalid(f"{path} is outside the closed catalogue")
    return value


def _self_hash(mapping: dict[str, object], field: str) -> str:
    preimage = dict(mapping)
    preimage[field] = None
    return _sha(_canonical(preimage))



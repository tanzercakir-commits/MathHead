def _is_profile(result: ExecutionDispositionResult, profile: str) -> bool:
    request_valid = (
        result.disposition_request_sha256 is not None
        and result.invocation_sha256 is not None
        and type(result.cancellation_armed) is bool
    )
    common_null = (
        result.base_parent_budget_sha256 is None
        and result.anchored_parent_budget_sha256 is None
        and result.portfolio_request_sha256 is None
    )
    if profile == "empty":
        return (
            result.disposition_request_sha256 is None
            and result.invocation_sha256 is None
            and result.cancellation_armed is None
            and result.cancellation_intent_sha256 is None
            and common_null
            and result.planning_result_sha256 is None
            and result.route_status is None
            and result.route_reason_code is None
            and result.planning_status is None
            and result.planning_reason_code is None
        )
    if profile == "validated_pre_route":
        return (
            request_valid
            and common_null
            and result.planning_result_sha256 is None
            and result.route_status is None
            and result.route_reason_code is None
            and result.planning_status is None
            and result.planning_reason_code is None
        )
    if profile == "invalid_route":
        return (
            request_valid
            and common_null
            and result.planning_result_sha256 is None
            and (result.route_status, result.route_reason_code) == ("invalid", "INVALID_INPUT")
            and result.planning_status is None
            and result.planning_reason_code is None
        )
    planned = (
        request_valid
        and result.planning_result_sha256 is not None
        and (result.route_status, result.route_reason_code) == ("routed", "ROUTED")
        and (result.planning_status, result.planning_reason_code) == ("planned", "PLANNED")
    )
    if profile == "invalid_planning":
        return (
            request_valid
            and common_null
            and result.planning_result_sha256 is not None
            and (result.route_status, result.route_reason_code) == ("routed", "ROUTED")
            and (result.planning_status, result.planning_reason_code)
            == ("invalid", "INVALID_INPUT")
        )
    if profile == "planned_no_budget":
        return planned and common_null
    if profile == "planned_unanchored":
        return (
            planned
            and result.base_parent_budget_sha256 is not None
            and result.anchored_parent_budget_sha256 is None
            and result.portfolio_request_sha256 is None
        )
    if profile == "planned_anchored":
        return (
            planned
            and result.base_parent_budget_sha256 is not None
            and result.anchored_parent_budget_sha256 is not None
            and result.portfolio_request_sha256 is None
        )
    if profile == "planned_ready":
        return (
            planned
            and result.base_parent_budget_sha256 is not None
            and result.anchored_parent_budget_sha256 is not None
            and result.portfolio_request_sha256 is not None
        )
    if profile == "early":
        return (
            request_valid
            and common_null
            and result.planning_result_sha256 is not None
            and result.cancellation_armed is False
            and result.cancellation_intent_sha256 is None
        )
    return False


def _validate_request_gate(result: ExecutionDispositionResult) -> None:
    observed = (
        result.disposition_request_sha256,
        result.invocation_sha256,
        result.cancellation_armed,
        result.cancellation_intent_sha256,
    )
    valid = (
        observed == (None, None, None, None)
        or (
            type(observed[0]) is str
            and type(observed[1]) is str
            and observed[2] is False
            and observed[3] is None
        )
        or all(type(item) is expected for item, expected in zip(observed, (str, str, bool, str)))
        and observed[2] is True
    )
    if not valid:
        raise _Invalid("result request/intent gate differs")


def _validate_state(result: ExecutionDispositionResult) -> None:
    no_report = (
        result.logical_report_sha256 is None
        and result.portfolio_result_sha256 is None
        and result.execution_provenance_sha256 is None
        and result.portfolio_status is None
        and result.portfolio_reason_code is None
    )
    if result.execution_state == "not_started":
        if not (
            result.portfolio_relation == "not_available"
            and result.audit_manifest_sha256 is None
            and no_report
            and result.replay_result_sha256 is None
            and result.replay_status is None
            and result.replay_reason_code is None
        ):
            raise _Invalid("not-started evidence shape differs")
        return
    started = _is_profile(result, "planned_ready")
    if not started:
        raise _Invalid("started result lacks complete prelaunch identities")
    if result.execution_state == "attempted_no_bundle":
        if not (
            result.portfolio_relation == "not_available"
            and result.audit_manifest_sha256 is None
            and no_report
            and result.replay_result_sha256 is None
            and result.replay_status is None
            and result.replay_reason_code is None
        ):
            raise _Invalid("attempted-no-bundle evidence shape differs")
    elif result.execution_state == "bundle_replay_failed":
        expected_reason = {"invalid": "REPLAY_INVALID", "exhausted": "REPLAY_BUDGET_EXHAUSTED"}.get(
            result.replay_status
        )
        if not (
            result.portfolio_relation == "not_available"
            and result.audit_manifest_sha256 is not None
            and no_report
            and result.replay_result_sha256 is not None
            and expected_reason is not None
            and result.replay_reason_code == expected_reason
        ):
            raise _Invalid("replay-failed evidence shape differs")
    elif result.execution_state == "replayed_complete":
        if not (
            result.portfolio_relation in {"exact", "invalid"}
            and all(
                item is not None
                for item in (
                    result.audit_manifest_sha256,
                    result.logical_report_sha256,
                    result.replay_result_sha256,
                    result.portfolio_result_sha256,
                    result.execution_provenance_sha256,
                    result.portfolio_status,
                    result.portfolio_reason_code,
                )
            )
            and (result.replay_status, result.replay_reason_code) == ("complete", "REPLAY_COMPLETE")
            and result.portfolio_reason_code
            in _PORTFOLIO_PAIRS.get(result.portfolio_status or "", set())
        ):
            raise _Invalid("replayed-complete evidence shape differs")
    else:
        raise _Invalid("unknown execution state")


def _validate_outcome_and_selection(result: ExecutionDispositionResult) -> None:
    discriminator: set[str | None]
    if (
        result.portfolio_relation == "exact"
        and result.portfolio_status in {"failed", "verifier_failed"}
        and result.portfolio_reason_code == "LAUNCH_FAILED"
    ):
        discriminator = {"launch_refused"}
    elif (
        result.portfolio_relation == "exact"
        and result.portfolio_status in {"failed", "verifier_failed"}
        and result.portfolio_reason_code == "EXECUTABLE_INVALID"
    ):
        discriminator = {"executable_refused", "executable_invalid"}
    elif (
        result.portfolio_relation == "exact"
        and result.portfolio_status == "inconclusive"
        and result.portfolio_reason_code == "CHECKER_INCONCLUSIVE"
    ):
        discriminator = {"certificate_unsupported", "certificate_inconclusive"}
    else:
        discriminator = {None}
    if result.portfolio_outcome_kind not in discriminator:
        raise _Invalid("portfolio outcome discriminator differs")
    selected = (
        result.selected_strategy_sha256,
        result.selected_evidence_sha256,
        result.selected_certificate_sha256,
        result.selected_checker_decision_sha256,
    )
    if result.classification.cause in {"checked_proof", "checked_refutation"}:
        if (
            result.execution_state != "replayed_complete"
            or any(item is None for item in selected)
            or result.linked_authority_tier
            not in {"checker_attestation", "external_proof_assistant"}
        ):
            raise _Invalid("checked selection identities differ")
    elif any(item is not None for item in selected) or result.linked_authority_tier != "none":
        raise _Invalid("non-checked result carries selected authority")


def _validate_terminal(result: ExecutionDispositionResult) -> None:
    classification = result.classification
    cause = classification.cause
    phase = classification.phase
    diagnostics = result.diagnostics
    if cause in {"invalid_request", "internal_error"}:
        if len(diagnostics) != 1 or diagnostics[0].phase != phase:
            raise _Invalid("invalid/internal result lacks its exact diagnostic")
    elif diagnostics:
        raise _Invalid("ordinary result carries a diagnostic")

    if cause == "invalid_request":
        if result.execution_state != "not_started":
            raise _Invalid("invalid request started execution")
        code = diagnostics[0].code
        valid = (
            (code == "REQUEST_INVALID" and phase == "request" and _is_profile(result, "empty"))
            or (
                code in {"INTENT_EVENT_MISMATCH", "BINDING_INPUT_INVALID", "ARTIFACT_INPUT_INVALID"}
                and phase == "request"
                and _is_profile(result, "validated_pre_route")
            )
            or (
                code == "ROUTE_INPUT_INVALID"
                and phase == "routing"
                and (
                    _is_profile(result, "validated_pre_route")
                    or _is_profile(result, "invalid_route")
                )
            )
            or (
                code in {"PLANNING_INPUT_INVALID", "ARTIFACT_INPUT_INVALID"}
                and phase == "planning"
                and _is_profile(result, "invalid_planning")
            )
            or (
                code == "BINDING_INPUT_INVALID"
                and phase == "planning"
                and _is_profile(result, "planned_no_budget")
            )
            or (
                code == "EXECUTION_INPUT_INVALID"
                and phase == "coordinator"
                and _is_profile(result, "planned_no_budget")
            )
            or (
                code == "RESERVED_EXTENSION_COLLISION"
                and phase == "coordinator"
                and _is_profile(result, "planned_unanchored")
            )
        )
        if not valid:
            raise _Invalid("invalid-request milestone or code differs")
        return

    if cause == "internal_error":
        code = diagnostics[0].code
        pair = (result.portfolio_status, result.portfolio_reason_code)
        valid = (
            (
                code == "AUDITED_EXECUTION_INVALID"
                and phase == "audit"
                and result.execution_state == "attempted_no_bundle"
                and result.portfolio_relation == "not_available"
            )
            or (
                code == "AUDIT_RELATION_INVALID"
                and phase == "audit"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "invalid"
            )
            or (
                code in {"AUDIT_REPLAY_INVALID", "AUDIT_REPLAY_EXHAUSTED"}
                and phase == "replay"
                and result.execution_state == "bundle_replay_failed"
            )
            or (
                code == "BUDGET_ANCHOR_INVALID"
                and phase == "coordinator"
                and result.execution_state == "not_started"
                and _is_profile(result, "planned_unanchored")
            )
            or (
                code == "PORTFOLIO_REQUEST_INVALID"
                and phase == "coordinator"
                and result.execution_state == "not_started"
                and _is_profile(result, "planned_anchored")
            )
            or (
                code == "COORDINATOR_LIMIT_EXHAUSTED"
                and phase == "coordinator"
                and result.execution_state == "not_started"
                and _is_profile(result, "empty")
            )
            or (
                code == "CLEANUP_INVARIANT"
                and phase == "cleanup"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "TREE_CLEANUP_FAILED"
                and pair[0] in {"failed", "verifier_failed"}
            )
            or (
                code == "SUPERVISOR_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "SUPERVISOR_FAILED"
                and pair[0] in {"failed", "verifier_failed"}
            )
            or (
                code == "WORKER_REQUEST_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "REQUEST_INVALID"
                and pair[0] in {"failed", "verifier_failed"}
            )
            or (
                code == "WORKER_PLAN_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "PLAN_INVALID"
                and pair[0] in {"failed", "verifier_failed"}
            )
            or (
                code == "WORKER_STRATEGY_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "STRATEGY_MISMATCH"
                and pair[0] in {"failed", "verifier_failed"}
            )
            or (
                code == "WORKER_BUDGET_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "BUDGET_INVALID"
                and pair[0] in {"failed", "verifier_failed"}
            )
            or (
                code == "WORKER_EXECUTABLE_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair[1] == "EXECUTABLE_INVALID"
                and pair[0] in {"failed", "verifier_failed"}
                and result.portfolio_outcome_kind == "executable_invalid"
            )
            or (
                code == "PORTFOLIO_INPUT_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair == ("invalid", "PORTFOLIO_INPUT_INVALID")
            )
            or (
                code == "PORTFOLIO_EXECUTION_INVARIANT"
                and phase == "coordinator"
                and result.execution_state == "replayed_complete"
                and result.portfolio_relation == "exact"
                and pair == ("invalid", "PORTFOLIO_EXECUTION_INVALID")
            )
        )
        if not valid:
            raise _Invalid("internal-error milestone, pair, or diagnostic differs")
        return

    if result.execution_state == "not_started":
        if not _is_profile(result, "early"):
            raise _Invalid("early ordinary result milestone differs")
        early = (
            (
                cause == "ambiguity"
                and phase == "routing"
                and result.route_status == "ambiguous"
                and result.route_reason_code in {"NON_UNIQUE_SELECTION", "READING_AMBIGUOUS"}
                and (result.planning_status, result.planning_reason_code)
                == ("ambiguous", "ROUTE_AMBIGUOUS")
            )
            or (
                cause == "budget_exhaustion"
                and phase == "routing"
                and (result.route_status, result.route_reason_code)
                == ("exhausted", "BUDGET_EXHAUSTED")
                and (result.planning_status, result.planning_reason_code)
                == ("exhausted", "ROUTE_EXHAUSTED")
            )
            or (
                cause == "budget_exhaustion"
                and phase == "planning"
                and (result.route_status, result.route_reason_code) == ("routed", "ROUTED")
                and (result.planning_status, result.planning_reason_code)
                == ("exhausted", "PLANNING_EXHAUSTED")
            )
            or (
                cause in {"unsupported_input", "unsupported_execution_environment"}
                and phase == "routing"
                and (result.route_status, result.route_reason_code)
                == ("unsupported", "NO_COMPATIBLE_CAPABILITY")
                and (result.planning_status, result.planning_reason_code)
                == ("unsupported", "ROUTE_UNSUPPORTED")
            )
        )
        if not early or classification.resource_dimensions:
            raise _Invalid("early ordinary classification differs")
        return

    if result.execution_state != "replayed_complete" or result.portfolio_relation != "exact":
        raise _Invalid("ordinary audited result is not exact and replay-complete")
    status, reason = result.portfolio_status, result.portfolio_reason_code
    expected: tuple[str, str, tuple[str, ...]] | None = None
    if (status, reason) == ("succeeded", "CHECKED_PROOF"):
        expected = ("checked_proof", "completed", ())
    elif (status, reason) == ("succeeded", "CHECKED_REFUTATION"):
        expected = ("checked_refutation", "completed", ())
    elif (status, reason) == ("ambiguous", "EVIDENCE_INCOMPLETE"):
        expected = ("ambiguity", "producer", ())
    elif (
        reason == "CANCELLED"
        and status == "cancelled"
        and cause in {"user_cancellation", "parent_cancellation", "supervisor_cancellation"}
    ):
        expected = (cause, phase, ())
        if (
            phase not in {"producer", "checker"}
            or result.cancellation_armed is not True
            or result.cancellation_intent_sha256 is None
        ):
            expected = None
    elif status == "exhausted" and reason in {
        "BUDGET_INSUFFICIENT",
        "WALL_TIME_EXHAUSTED",
        "CPU_TIME_EXHAUSTED",
        "MEMORY_EXHAUSTED",
        "OUTPUT_EXHAUSTED",
        "DIAGNOSTIC_EXHAUSTED",
    }:
        static = {
            "WALL_TIME_EXHAUSTED": ("wall_time_us",),
            "CPU_TIME_EXHAUSTED": ("cpu_time_us",),
            "MEMORY_EXHAUSTED": ("memory_bytes",),
            "OUTPUT_EXHAUSTED": ("output_bytes",),
            "DIAGNOSTIC_EXHAUSTED": ("diagnostic_bytes",),
        }
        dimensions = (
            classification.resource_dimensions
            if reason == "BUDGET_INSUFFICIENT"
            else static[reason]
        )
        expected = ("budget_exhaustion", phase, dimensions)
        if phase not in {"producer", "checker"} or not dimensions:
            expected = None
    elif (status, reason) == ("unsupported", "ISOLATION_UNSUPPORTED"):
        expected = ("unsupported_execution_environment", "producer", ())
    elif (status, reason) == ("inconclusive", "ISOLATION_UNSUPPORTED"):
        expected = ("unsupported_execution_environment", "checker", ())
    elif (
        (status, reason) == ("unsupported", "EVIDENCE_UNSUPPORTED")
        or (status, reason) == ("exhausted", "EVIDENCE_EXHAUSTED")
        or (status, reason) == ("cancelled", "EVIDENCE_CANCELLED")
    ):
        expected = ("producer_refusal", "producer", ())
    elif (status, reason) == ("exhausted", "CHECKER_EXHAUSTED") or (status, reason) == (
        "cancelled",
        "CHECKER_CANCELLED",
    ):
        expected = ("verifier_refusal", "checker", ())
    elif (status, reason) == ("inconclusive", "CHECKER_INCONCLUSIVE"):
        if result.portfolio_outcome_kind == "certificate_unsupported":
            expected = ("verifier_refusal", "checker", ())
        elif result.portfolio_outcome_kind == "certificate_inconclusive":
            expected = ("inconclusive_execution", "checker", ())
    elif status == "truncated" and reason in {"EVIDENCE_TRUNCATED", "CHECKER_TRUNCATED"}:
        expected = ("truncation", "producer" if reason == "EVIDENCE_TRUNCATED" else "checker", ())
    elif status == "disagreement" and reason in {"CHECKER_REJECTED", "CHECKER_DISAGREED"}:
        expected = ("checker_disagreement", "checker", ())
    elif status == "invalid_evidence" and reason in {
        "EVIDENCE_INVALID",
        "EVIDENCE_PROTOCOL_LIMIT",
        "CERTIFICATE_INVALID",
    }:
        expected = (
            "invalid_evidence",
            "checker" if reason == "CERTIFICATE_INVALID" else "producer",
            (),
        )
    elif status == "failed" and reason in {
        "LAUNCH_FAILED",
        "EXIT_FAILED",
        "PROTOCOL_FAILED",
        "EVIDENCE_ERROR",
    }:
        expected = ("producer_failure", "producer", ())
    elif status == "verifier_failed" and reason in {
        "LAUNCH_FAILED",
        "EXIT_FAILED",
        "PROTOCOL_FAILED",
        "CERTIFICATE_INVALID",
    }:
        expected = ("verifier_failure", "checker", ())
    elif (
        reason == "EXECUTABLE_INVALID"
        and status in {"failed", "verifier_failed"}
        and result.portfolio_outcome_kind == "executable_refused"
    ):
        expected = (
            "producer_refusal" if status == "failed" else "verifier_refusal",
            "producer" if status == "failed" else "checker",
            (),
        )
    if expected is None or (cause, phase, classification.resource_dimensions) != expected:
        raise _Invalid("ordinary portfolio classification differs")


def _validate_retained_relations(result: ExecutionDispositionResult) -> None:
    if result._request_input is not None:
        raise _Invalid("raw disposition-request bytes are never retained")
    if result._request is None:
        if result.disposition_request_sha256 is not None:
            if result._request_input is not None:
                raise _Invalid("validated request is absent for a retained valid projection")
    else:
        validate_execution_disposition_request(result._request)
        if result.request_input_sha256 != _sha(
            execution_disposition_request_bytes(result._request)
        ):
            raise _Invalid("retained request differs from the exact raw request identity")
        intent_sha = (
            None
            if result._request.cancellation_intent is None
            else result._request.cancellation_intent.intent_sha256
        )
        if (
            result.disposition_request_sha256,
            result.invocation_sha256,
            result.cancellation_armed,
            result.cancellation_intent_sha256,
        ) != (
            result._request.request_sha256,
            result._request.invocation_sha256,
            result._request.cancellation_armed,
            intent_sha,
        ):
            raise _Invalid("result request projection differs")
        if (
            result.base_parent_budget_sha256 is not None
            and result.base_parent_budget_sha256 != result._request.base_parent_budget_sha256
        ):
            raise _Invalid("result base budget differs from request")
        if (
            result.planning_result_sha256 is not None
            and result.planning_result_sha256 != result._request.planning_result_sha256
        ):
            raise _Invalid("result planning identity differs from request")
        if result.classification.cause in {
            "user_cancellation",
            "parent_cancellation",
            "supervisor_cancellation",
        }:
            expected_origin = result.classification.cause.removesuffix("_cancellation")
            if (
                result._request.cancellation_intent is None
                or result._request.cancellation_intent.origin_source != expected_origin
            ):
                raise _Invalid("cancellation result origin differs from committed intent")
    if result._anchored_parent_budget is not None and result.anchored_parent_budget_sha256 != _sha(
        result._anchored_parent_budget
    ):
        raise _Invalid("retained anchored parent budget differs")
    if result._anchored_parent_budget is not None:
        if result._request is None or result.base_parent_budget_sha256 is None:
            raise _Invalid("retained anchor has no validated request or base identity")
        anchored_value = _parse(result._anchored_parent_budget, "anchored_parent_budget")
        extensions = anchored_value.get("extensions")
        expected_extension = {"disposition_request_sha256": result._request.request_sha256}
        if type(extensions) is not dict or extensions.get(RESERVED_EXTENSION) != expected_extension:
            raise _Invalid("retained budget anchor extension differs")
        del extensions[RESERVED_EXTENSION]
        stripped = _canonical(anchored_value)
        _parse_parent_budget(stripped)
        if _sha(stripped) != result.base_parent_budget_sha256:
            raise _Invalid("retained budget anchor does not strip to the base identity")
    if result._portfolio_request is not None and result.portfolio_request_sha256 != _sha(
        result._portfolio_request
    ):
        raise _Invalid("retained portfolio request differs")
    if result._portfolio_request is not None:
        request_value = parse_proof_search_portfolio_request(result._portfolio_request)
        if (
            result._anchored_parent_budget is None
            or request_value.parent_budget_sha256 != _sha(result._anchored_parent_budget)
            or request_value.planning_result_sha256 != result.planning_result_sha256
        ):
            raise _Invalid("retained portfolio request input relation differs")
    if result._audit is not None:
        if type(result._audit) is not RunAuditBundle or result.audit_manifest_sha256 != _sha(
            result._audit.manifest
        ):
            raise _Invalid("retained audit bundle identity differs")
        _shallow_audit_bundle(result._audit)
    if result._replay is not None:
        if (
            type(result._replay) is not RunAuditReplayResult
            or result.replay_result_sha256 != result._replay.replay_result_sha256
        ):
            raise _Invalid("retained replay result identity differs")
        if result._audit is None:
            raise _Invalid("retained replay has no audit bundle")
        _shallow_replay(result._replay, result._audit)
        if result._replay.status == "complete":
            logical = _parse(result._audit.logical_report, "logical_report")
            manifest = _parse(result._audit.manifest, "manifest")
            selected = (
                result.selected_strategy_sha256,
                result.selected_evidence_sha256,
                result.selected_certificate_sha256,
                result.selected_checker_decision_sha256,
            )
            logical_selected = tuple(
                logical.get(name)
                for name in (
                    "selected_strategy_sha256",
                    "selected_evidence_sha256",
                    "selected_certificate_sha256",
                    "selected_checker_decision_sha256",
                )
            )
            if (
                result.logical_report_sha256 != _sha(result._audit.logical_report)
                or result.portfolio_result_sha256 != manifest.get("portfolio_result_sha256")
                or result.execution_provenance_sha256 != manifest.get("execution_provenance_sha256")
                or (result.portfolio_status, result.portfolio_reason_code)
                != (logical.get("status"), logical.get("reason_code"))
                or (
                    result.portfolio_relation == "exact"
                    and (
                        selected != logical_selected
                        or result.linked_authority_tier != logical.get("authority_tier")
                    )
                )
            ):
                raise _Invalid("retained complete audit projection differs")
    # A failed replay is represented only by the bounded hashes and closed
    # status in the result.  Its unvalidated manifest/object inputs are never
    # retained in the public bundle.
    expected_audit = result.execution_state == "replayed_complete"
    expected_replay = expected_audit
    if (result._audit is not None) != expected_audit or (
        result._replay is not None
    ) != expected_replay:
        raise _Invalid("retained audit/replay values differ from execution state")



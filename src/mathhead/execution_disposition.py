def _unsupported_cause(
    route: CapabilityRouteResult,
    planning_request: bytes,
    descriptors: tuple[bytes, ...],
) -> str:
    if route.status != "unsupported" or route.reason_code != "NO_COMPATIBLE_CAPABILITY":
        raise _Invalid("route is not the closed unsupported pair")
    if not descriptors or route.registry is None or not route.registry.entries:
        return "unsupported_execution_environment"
    planning = parse_planning_request(planning_request)
    route_request = planning.route_request
    routed_request = parse_capability_route_request(route_request)
    descriptor_values = {_sha(raw): _parse(raw, "descriptor") for raw in descriptors}
    for incompatibility in route.incompatibilities:
        reasons = set(incompatibility.reason_codes)
        structural = reasons & _STRUCTURAL_BLOCKERS
        availability = reasons & _AVAILABILITY_BLOCKERS
        if "REPLAY_MODE_UNAVAILABLE" in reasons:
            descriptor = descriptor_values.get(incompatibility.descriptor_sha256)
            if descriptor is None:
                raise _Invalid("unsupported route descriptor is absent")
            operations = descriptor.get("operations")
            replay = descriptor.get("replay")
            if type(operations) is not list or type(replay) is not dict:
                raise _Invalid("unsupported route replay declarations are malformed")
            operation = next(
                (
                    item
                    for item in operations
                    if type(item) is dict and item.get("operation") == routed_request.operation
                ),
                None,
            )
            operation_modes = set() if operation is None else set(operation.get("replay_modes", []))
            plugin_modes = set(replay.get("supported_modes", []))
            ambient_modes = set(routed_request.availability.replay_modes)
            mode = routed_request.replay_mode
            if mode not in operation_modes or mode not in plugin_modes:
                structural.add("REPLAY_MODE_UNAVAILABLE")
            elif mode not in ambient_modes:
                availability.add("REPLAY_MODE_UNAVAILABLE")
            else:
                raise _Invalid("retained replay-mode incompatibility is impossible")
        if not structural and not availability:
            raise _Invalid("unsupported route has an ungoverned incompatibility")
        if not structural and availability:
            return "unsupported_execution_environment"
    if route.incompatibilities:
        return "unsupported_input"
    raise _Invalid("unsupported route has no incompatibilities")


def _validate_input_collections(
    semantic_inputs: tuple[bytes, ...],
    descriptors: tuple[bytes, ...],
    bindings: tuple[bytes, ...],
    artifacts: tuple[tuple[str, bytes], ...],
) -> tuple[bytes, ...]:
    if type(descriptors) is not tuple:
        raise _Invalid("descriptors must be one exact tuple")
    if type(bindings) is not tuple:
        raise _Invalid("bindings must be one exact tuple")
    if type(artifacts) is not tuple:
        raise _Invalid("artifacts must be one exact tuple")
    if len(descriptors) > MAX_DESCRIPTORS:
        raise _Exhausted("descriptor count ceiling exceeded")
    if len(bindings) > MAX_BINDINGS:
        raise _Exhausted("binding count ceiling exceeded")
    if len(artifacts) > MAX_ARTIFACTS:
        raise _Exhausted("artifact count ceiling exceeded")
    if any(type(raw) is not bytes for raw in (*semantic_inputs, *descriptors, *bindings)):
        raise _Invalid("descriptor and binding elements must be exact bytes")
    if any(len(raw) > MAX_INPUT_BYTES for raw in (*semantic_inputs, *descriptors, *bindings)):
        raise _Exhausted("semantic input byte ceiling exceeded")
    descriptor_bytes = sum(len(raw) for raw in descriptors)
    if descriptor_bytes > MAX_AGGREGATE_DESCRIPTOR_BYTES:
        raise _Exhausted("aggregate descriptor byte ceiling exceeded")
    total = (
        sum(len(raw) for raw in semantic_inputs)
        + descriptor_bytes
        + sum(len(raw) for raw in bindings)
    )
    if total > MAX_AGGREGATE_INPUT_BYTES:
        raise _Exhausted("aggregate semantic input byte ceiling exceeded")
    artifact_bytes: list[bytes] = []
    artifact_total = 0
    roles: set[str] = set()
    for index, pair in enumerate(artifacts):
        if (
            type(pair) is not tuple
            or len(pair) != 2
            or type(pair[0]) is not str
            or _ID.fullmatch(pair[0]) is None
            or type(pair[1]) is not bytes
        ):
            raise _Invalid(f"artifacts[{index}] must be an exact role/bytes pair")
        if len(pair[1]) > MAX_ARTIFACT_BYTES:
            raise _Exhausted(f"artifacts[{index}] byte ceiling exceeded")
        if pair[0] in roles:
            raise _Invalid("artifact roles must be unique")
        roles.add(pair[0])
        artifact_bytes.append(pair[1])
        artifact_total += len(pair[1])
        if artifact_total > MAX_AGGREGATE_ARTIFACT_BYTES:
            raise _Exhausted("aggregate artifact byte ceiling exceeded")
        total += len(pair[1])
        if total > MAX_AGGREGATE_INPUT_BYTES:
            raise _Exhausted("aggregate semantic input byte ceiling exceeded")
    return tuple(artifact_bytes)


def _validate_effect_string_ceilings(
    executable_paths: tuple[tuple[str, str], ...],
    workspace_root: str | None,
) -> None:
    if len(executable_paths) > MAX_EXECUTABLE_PATHS:
        raise _Exhausted("executable path count ceiling exceeded")
    if type(workspace_root) is str and len(workspace_root) > MAX_STRING:
        raise _Exhausted("workspace string ceiling exceeded")
    for pair in executable_paths:
        if type(pair) is not tuple or len(pair) != 2:
            continue
        for value in pair:
            if type(value) is str and len(value) > MAX_STRING:
                raise _Exhausted("executable path string ceiling exceeded")


def _request_inventory_relation(
    request: ExecutionDispositionRequest,
    planning_request: bytes,
    route_result: bytes,
    planning_result: bytes,
    base_parent_budget: bytes | None,
    descriptors: tuple[bytes, ...],
    bindings: tuple[bytes, ...],
    artifacts: tuple[tuple[str, bytes], ...],
) -> str | None:
    if (
        request.planning_request_sha256 != _sha(planning_request)
        or request.route_result_sha256 != _sha(route_result)
        or request.planning_result_sha256 != _sha(planning_result)
        or request.base_parent_budget_sha256
        != (None if base_parent_budget is None else _sha(base_parent_budget))
        or request.descriptor_sha256s != tuple(sorted(_sha(raw) for raw in descriptors))
    ):
        return "REQUEST_INVALID"
    if request.binding_sha256s != tuple(_sha(raw) for raw in bindings):
        return "BINDING_INPUT_INVALID"
    observed_artifacts = tuple((role, _sha(raw), len(raw)) for role, raw in artifacts)
    expected_artifacts = tuple(
        (item.role, item.sha256, item.byte_count) for item in request.artifact_bindings
    )
    if observed_artifacts != expected_artifacts:
        return "ARTIFACT_INPUT_INVALID"
    return None


def _execution_inputs_valid(
    plan: PlanningResult,
    bindings: tuple[bytes, ...],
    artifacts: tuple[tuple[str, bytes], ...],
    executable_paths: tuple[tuple[str, str], ...],
    workspace_root: str | None,
) -> tuple[object, ...]:
    if len(bindings) != len(plan.strategies):
        raise ProofSearchPortfolioValidationError(
            "binding", "bindings", "one binding per strategy is required"
        )
    try:
        parsed = tuple(parse_portfolio_execution_binding(raw) for raw in bindings)
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception as exc:
        raise ProofSearchPortfolioValidationError(
            "binding", "bindings", "execution binding is invalid"
        ) from exc
    artifact_map = {role: raw for role, raw in artifacts}
    for index, (strategy, binding) in enumerate(zip(plan.strategies, parsed)):
        if (
            strategy.plan_order != index
            or binding.plan_order != index
            or binding.strategy_sha256 != strategy.strategy_sha256
            or binding.descriptor_sha256 != strategy.descriptor_sha256
            or binding.producer_component_id != strategy.producer_component_id
            or binding.checker_component_id != strategy.checker_component_id
        ):
            raise ProofSearchPortfolioValidationError(
                "binding", f"bindings[{index}]", "binding and plan differ"
            )
        for artifact in binding.input_artifacts:
            raw = artifact_map.get(artifact.role)
            if raw is None or _sha(raw) != artifact.sha256 or len(raw) != artifact.bytes:
                raise ProofSearchPortfolioValidationError(
                    "artifact",
                    f"bindings[{index}].input_artifacts",
                    "binding artifact differs",
                )
    if type(executable_paths) is not tuple or type(workspace_root) is not str or not workspace_root:
        raise _Invalid("planned execution needs exact paths and nonempty workspace")
    paths: dict[str, str] = {}
    for index, pair in enumerate(executable_paths):
        if (
            type(pair) is not tuple
            or len(pair) != 2
            or type(pair[0]) is not str
            or _DIGEST.fullmatch(pair[0]) is None
            or type(pair[1]) is not str
            or not pair[1]
            or pair[0] in paths
        ):
            raise _Invalid(f"executable_paths[{index}] is malformed or duplicated")
        paths[pair[0]] = pair[1]
    expected_paths = {
        digest
        for binding in parsed
        for digest in (binding.producer_executable_sha256, binding.checker_executable_sha256)
    }
    if set(paths) != expected_paths:
        raise _Invalid("executable path inventory is missing or surplus")
    return parsed


def _audit_inventory(
    audit: RunAuditBundle,
) -> tuple[dict[str, object], dict[str, bytes], dict[str, dict[str, object]]]:
    manifest = _parse(audit.manifest, "manifest")
    raw_records = manifest.get("objects")
    if type(raw_records) is not list:
        raise _Invalid("audit manifest object records are absent")
    physical = {_sha(raw): raw for raw in audit.objects}
    by_id: dict[str, dict[str, object]] = {}
    for raw in raw_records:
        if type(raw) is not dict:
            raise _Invalid("audit object record is not an object")
        role_id = raw.get("role_id")
        digest = raw.get("sha256")
        if (
            type(role_id) is not str
            or type(digest) is not str
            or digest not in physical
            or role_id in by_id
        ):
            raise _Invalid("audit record identity closure differs")
        by_id[role_id] = raw
    return manifest, physical, by_id


def _record_bytes(
    physical: dict[str, bytes], by_id: dict[str, dict[str, object]], role_id: str
) -> bytes:
    record = by_id.get(role_id)
    if record is None or type(record.get("sha256")) is not str:
        raise _Invalid(f"audit role {role_id} is absent")
    raw = physical.get(str(record["sha256"]))
    if raw is None:
        raise _Invalid(f"audit role {role_id} has no physical object")
    return raw


def _portfolio_from_audit(
    audit: RunAuditBundle,
) -> tuple[
    dict[str, object],
    dict[str, object],
    ProofSearchPortfolioResult,
    dict[str, bytes],
    dict[str, dict[str, object]],
    bytes,
]:
    manifest, physical, by_id = _audit_inventory(audit)
    logical_raw = _record_bytes(physical, by_id, "logical_report")
    logical = _parse(logical_raw, "logical_report")
    portfolio_raw = _record_bytes(physical, by_id, "portfolio_result")
    final_budget = _record_bytes(physical, by_id, "final_parent_budget")
    portfolio_projection = _parse(portfolio_raw, "portfolio_result")
    selected_evidence = None
    selected_certificate = None
    if logical.get("selected_evidence_sha256") is not None:
        selected_evidence = next(
            (raw for raw in physical.values() if _sha(raw) == logical["selected_evidence_sha256"]),
            None,
        )
    if logical.get("selected_certificate_sha256") is not None:
        selected_certificate = next(
            (
                raw
                for raw in physical.values()
                if _sha(raw) == logical["selected_certificate_sha256"]
            ),
            None,
        )
    portfolio = parse_proof_search_portfolio_result(
        portfolio_raw,
        final_parent_budget=(
            None if portfolio_projection.get("final_parent_budget_sha256") is None else final_budget
        ),
        selected_evidence=selected_evidence,
        selected_certificate=selected_certificate,
    )
    if len(portfolio.attempts) > MAX_ATTEMPTS:
        raise _Exhausted("portfolio attempt count budget exceeded")
    return manifest, logical, portfolio, physical, by_id, final_budget


def _terminal_phase(portfolio: ProofSearchPortfolioResult) -> str:
    if not portfolio.attempts:
        raise _Invalid("terminal portfolio has no final attempt")
    attempt = portfolio.attempts[-1]
    checker_reasons = {
        "CHECKER_EXHAUSTED",
        "CHECKER_CANCELLED",
        "CHECKER_TRUNCATED",
        "CHECKER_INCONCLUSIVE",
        "CHECKER_REJECTED",
        "CHECKER_DISAGREED",
        "CERTIFICATE_INVALID",
    }
    if (
        portfolio.status == "verifier_failed"
        or portfolio.reason_code in checker_reasons
        or (
            attempt.checker_status != "not_started"
            and attempt.checker_reason_code == portfolio.reason_code
        )
    ):
        return "checker"
    return "producer"


def _terminal_observation(
    portfolio: ProofSearchPortfolioResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    phase: str,
) -> dict[str, object]:
    attempt = portfolio.attempts[-1]
    role_id = f"{phase}_worker_observation_{attempt.attempt_order:06d}"
    observation = _parse(_record_bytes(physical, by_id, role_id), role_id)
    result = observation.get("result")
    if type(result) is not dict:
        raise _Invalid("terminal worker observation result is absent")
    expected_status = attempt.producer_status if phase == "producer" else attempt.checker_status
    expected_reason = (
        attempt.producer_reason_code if phase == "producer" else attempt.checker_reason_code
    )
    if (
        result.get("status") != expected_status
        or result.get("reason_code") != expected_reason
        or result.get("strategy_sha256") != attempt.strategy_sha256
    ):
        raise _Invalid("terminal attempt and worker observation differ")
    return result


def _budget_dimensions(
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    phase: str,
) -> tuple[str, ...]:
    attempt = portfolio.attempts[-1]
    ledger_sha, ledger_after_sha = _terminal_worker_ledgers(portfolio, physical, by_id, phase)
    if ledger_sha != ledger_after_sha:
        raise _Invalid("BUDGET_INSUFFICIENT changed the relevant parent ledger")
    raw = physical.get(ledger_sha)
    if raw is None:
        raise _Invalid("parent-before ledger object is absent")
    state = _parse_parent_budget(raw)
    strategy = next(
        (item for item in plan.strategies if item.strategy_sha256 == attempt.strategy_sha256),
        None,
    )
    if strategy is None:
        raise _Invalid("terminal strategy is absent from fresh plan")
    requested = {
        name: getattr(strategy.resource_request.requested, name) for name in RESOURCE_DIMENSIONS
    }
    limits = state.value.get("limits")
    if type(limits) is not dict:
        raise _Invalid("parent-before ledger limits are absent")
    active = {name: 0 for name in RESOURCE_DIMENSIONS}
    for lease in state.active.values():
        allocation = lease.get("allocation")
        if type(allocation) is not dict:
            raise _Invalid("active ledger allocation is malformed")
        for name in RESOURCE_DIMENSIONS:
            active[name] += int(allocation[name])
    effective = {
        **state.cumulative,
        "wall_time_us": state.observation["wall_time_us"],
        "memory_bytes": state.observation["memory_retained_bytes"],
        "nesting_depth": state.observation["nesting_current"],
    }
    unavailable = tuple(
        sorted(
            name
            for name in RESOURCE_DIMENSIONS
            if int(effective[name]) + active[name] + requested[name] > int(limits[name])
        )
    )
    if not unavailable:
        raise _Invalid("BUDGET_INSUFFICIENT has no unavailable dimension")
    return unavailable


def _checker_outcome_kind(
    portfolio: ProofSearchPortfolioResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
) -> str:
    attempt = portfolio.attempts[-1]
    if attempt.checker_decision_sha256 is None:
        raise _Invalid("CHECKER_INCONCLUSIVE has no checker decision")
    decision_raw = _record_bytes(physical, by_id, f"checker_decision_{attempt.attempt_order:06d}")
    certificate_raw = _record_bytes(
        physical, by_id, f"checker_certificate_{attempt.attempt_order:06d}"
    )
    decision = parse_portfolio_checker_decision(decision_raw, certificate_raw)
    if decision.decision_sha256 != attempt.checker_decision_sha256:
        raise _Invalid("checker decision semantic identity differs")
    if decision.certificate_verdict == "unsupported":
        return "certificate_unsupported"
    if decision.certificate_verdict == "inconclusive":
        return "certificate_inconclusive"
    raise _Invalid("CHECKER_INCONCLUSIVE certificate verdict is not governed")


def _terminal_worker_ledgers(
    portfolio: ProofSearchPortfolioResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    phase: str,
) -> tuple[str, str]:
    """Return the exact before/after ledger identities for the final worker."""
    if phase not in {"producer", "checker"} or not portfolio.attempts:
        raise _Invalid("terminal worker ledger phase differs")
    ledger_order = sum(
        1 + int(attempt.checker_worker_result_sha256 is not None)
        for attempt in portfolio.attempts[:-1]
    )
    attempt = portfolio.attempts[-1]
    producer_after = _record_bytes(physical, by_id, f"reconciled_parent_budget_{ledger_order:06d}")
    if phase == "producer":
        before = attempt.parent_budget_before_sha256
        after = _sha(producer_after)
    else:
        if attempt.checker_worker_result_sha256 is None:
            raise _Invalid("checker ledger requested for a nonstarted checker")
        checker_after = _record_bytes(
            physical, by_id, f"reconciled_parent_budget_{ledger_order + 1:06d}"
        )
        before = _sha(producer_after)
        after = _sha(checker_after)
    return before, after


def _terminal_transition_is_closed(
    portfolio: ProofSearchPortfolioResult, plan: PlanningResult
) -> bool:
    attempt = portfolio.attempts[-1]
    strategy = next(
        (item for item in plan.strategies if item.strategy_sha256 == attempt.strategy_sha256),
        None,
    )
    if strategy is None:
        return False
    transitions = tuple(item for item in strategy.transitions if item.outcome == attempt.outcome)
    return (
        len(transitions) == 1
        and transitions[0].transition_sha256 == attempt.transition_sha256
        and transitions[0].action != "fallback"
        and transitions[0].terminal_state == portfolio.status
    )


def _terminal_strategy(
    portfolio: ProofSearchPortfolioResult, plan: PlanningResult
) -> PlanningStrategy:
    attempt = portfolio.attempts[-1]
    strategy = next(
        (item for item in plan.strategies if item.strategy_sha256 == attempt.strategy_sha256),
        None,
    )
    if strategy is None:
        raise _Invalid("terminal strategy is absent from the fresh plan")
    return strategy


def _validate_worker_ledger_relation(
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    phase: str,
    result: dict[str, object],
    *,
    launched: bool,
) -> None:
    before_sha, after_sha = _terminal_worker_ledgers(portfolio, physical, by_id, phase)
    if launched:
        if (
            before_sha == after_sha
            or result.get("tree_terminated") is not True
            or result.get("lease_reconciled") is not True
        ):
            raise _Invalid("launched terminal worker lacks containment or reconciliation")
        before_raw = physical.get(before_sha)
        after_raw = physical.get(after_sha)
        if before_raw is None or after_raw is None:
            raise _Invalid("terminal worker ledger bytes are absent")
        before = _parse_parent_budget(before_raw)
        after = _parse_parent_budget(after_raw)
        strategy = _terminal_strategy(portfolio, plan)
        lease_id = (
            f"lease_portfolio_{strategy.plan_order}_{phase}_"
            f"{portfolio.attempts[-1].strategy_sha256[:16]}"
        )
        if lease_id in before.reconciliations or set(after.reconciliations) - set(
            before.reconciliations
        ) != {lease_id}:
            raise _Invalid("terminal worker reconciliation identity differs")
        reconciliation = after.reconciliations.get(lease_id)
        if reconciliation is None or type(reconciliation.get("event")) is not dict:
            raise _Invalid("terminal worker reconciliation event is absent")
        event = reconciliation["event"]
        expected_outcome = (
            "cancelled"
            if result.get("status") == "cancelled"
            else "exhausted"
            if result.get("status") == "exhausted"
            else "completed"
        )
        if event.get("child_outcome") != expected_outcome:
            raise _Invalid("terminal worker reconciliation outcome differs")
    elif (
        before_sha != after_sha
        or result.get("tree_terminated") is not False
        or result.get("lease_reconciled") is not False
        or result.get("artifacts") != []
    ):
        raise _Invalid("nonlaunched terminal worker changed execution state")


def _attempt_evidence_semantics(
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
) -> tuple[
    bytes | None,
    dict[str, object] | None,
    str | None,
    PlanningStrategy,
    dict[str, object],
    str,
    tuple[dict[str, object], ...],
]:
    attempt = portfolio.attempts[-1]
    strategy = _terminal_strategy(portfolio, plan)
    descriptor_raw = physical.get(strategy.descriptor_sha256)
    if descriptor_raw is None:
        raise _Invalid("terminal strategy descriptor bytes are absent")
    descriptors = _descriptor_inventory((descriptor_raw,))
    descriptor = descriptors.get(strategy.descriptor_sha256)
    if descriptor is None:
        raise _Invalid("terminal strategy descriptor identity differs")
    producer, checker, environment, certificate_formats = _descriptor_strategy_parts(
        descriptor, strategy
    )
    role_id = f"validated_evidence_{attempt.attempt_order:06d}"
    if attempt.evidence_sha256 is None:
        if role_id in by_id or attempt.evidence_bytes != 0:
            raise _Invalid("absent terminal Evidence retains an audit object")
        return (
            None,
            None,
            None,
            strategy,
            checker,
            environment,
            certificate_formats,
        )
    evidence_raw = _record_bytes(physical, by_id, role_id)
    if _sha(evidence_raw) != attempt.evidence_sha256 or len(evidence_raw) != attempt.evidence_bytes:
        raise _Invalid("terminal Evidence identity or length differs")
    evidence, evidence_status = _validate_evidence(
        evidence_raw,
        strategy,
        producer,
        environment,
    )
    return (
        evidence_raw,
        evidence,
        evidence_status,
        strategy,
        checker,
        environment,
        certificate_formats,
    )


def _attempt_checker_semantics(
    portfolio: ProofSearchPortfolioResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    evidence_raw: bytes,
    evidence: dict[str, object],
    claim: str,
    strategy: PlanningStrategy,
    checker: dict[str, object],
    environment: str,
    certificate_formats: tuple[dict[str, object], ...],
) -> tuple[str, object]:
    attempt = portfolio.attempts[-1]
    if attempt.checker_decision_sha256 is None:
        raise _Invalid("terminal checker decision identity is absent")
    decision_raw = _record_bytes(physical, by_id, f"checker_decision_{attempt.attempt_order:06d}")
    certificate_raw = _record_bytes(
        physical, by_id, f"checker_certificate_{attempt.attempt_order:06d}"
    )
    decision = parse_portfolio_checker_decision(decision_raw, certificate_raw)
    _certificate, verdict, authority = _validate_certificate(
        certificate_raw,
        evidence_raw,
        evidence,
        strategy,
        checker,
        environment,
        certificate_formats,
    )
    expected_decision_verdict = "invalid" if verdict == "disagreement" else verdict
    expected_reason = (
        "CHECKER_AGREED"
        if verdict == "verified" and decision.agreement
        else "CHECKER_DISAGREED"
        if verdict in {"verified", "disagreement"}
        else "CHECKER_REJECTED"
        if verdict == "invalid"
        else "CERTIFICATE_INVALID"
        if verdict == "verifier_failed"
        else "CHECKER_INCONCLUSIVE"
    )
    if (
        decision.decision_sha256 != attempt.checker_decision_sha256
        or decision.strategy_sha256 != portfolio.attempts[-1].strategy_sha256
        or decision.producer_component_id != strategy.producer_component_id
        or decision.checker_component_id != strategy.checker_component_id
        or decision.subject_sha256 != _sha(_canonical(evidence["subject"]))
        or decision.claim != claim
        or decision.evidence_sha256 != _sha(evidence_raw)
        or decision.evidence_bytes != len(evidence_raw)
        or decision.certificate_verdict != expected_decision_verdict
        or decision.certificate_authority != authority
        or decision.reason_code != expected_reason
    ):
        raise _Invalid("terminal checker decision and Certificate differ")
    return verdict, decision


def _require_unstarted_checker(
    portfolio: ProofSearchPortfolioResult,
    by_id: dict[str, dict[str, object]],
) -> None:
    attempt = portfolio.attempts[-1]
    order = attempt.attempt_order
    if (
        attempt.checker_worker_result_sha256 is not None
        or attempt.checker_status != "not_started"
        or attempt.checker_reason_code != "NOT_STARTED"
        or attempt.checker_decision_sha256 is not None
        or f"checker_worker_observation_{order:06d}" in by_id
        or f"checker_decision_{order:06d}" in by_id
        or f"checker_certificate_{order:06d}" in by_id
    ):
        raise _Invalid("terminal checker should not have started")


def _validate_completed_worker(
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    phase: str,
    *,
    retained_output: bool,
) -> dict[str, object]:
    result = _terminal_observation(portfolio, physical, by_id, phase)
    artifacts = result.get("artifacts")
    if (
        result.get("status") != "completed"
        or result.get("reason_code") != "COMPLETED"
        or type(artifacts) is not list
        or (len(artifacts) == 1) != retained_output
    ):
        raise _Invalid("completed terminal worker shape differs")
    _validate_worker_ledger_relation(portfolio, plan, physical, by_id, phase, result, launched=True)
    return result


def _validate_terminal_pair_relation(
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
) -> str:
    pair = (portfolio.status, portfolio.reason_code)
    relation = _TERMINAL_PAIR_RELATIONS.get(pair)
    if relation is None:
        raise _Invalid("portfolio pair has no terminal relation")
    expected_outcome, expected_phase, source = relation
    if not portfolio.attempts:
        raise _Invalid("terminal portfolio has no final attempt")
    attempt = portfolio.attempts[-1]
    if attempt.outcome != expected_outcome or not _terminal_transition_is_closed(portfolio, plan):
        raise _Invalid("outer portfolio pair and terminal transition differ")
    phase = expected_phase
    if phase == "either":
        if (
            attempt.checker_worker_result_sha256 is not None
            and attempt.checker_reason_code == portfolio.reason_code
        ):
            phase = "checker"
        elif attempt.producer_reason_code == portfolio.reason_code:
            phase = "producer"
        else:
            raise _Invalid("outer portfolio pair has no exact terminal worker role")

    if source.startswith("worker_") or source == "special_worker":
        result = _terminal_observation(portfolio, physical, by_id, phase)
        if result.get("reason_code") != portfolio.reason_code:
            raise _Invalid("outer portfolio reason is not the terminal worker reason")
        expected_status = {
            "worker_unsupported": "unsupported",
            "worker_budget_insufficient": "refused",
            "worker_exhausted": "exhausted",
            "worker_cancelled": "cancelled",
            "worker_invalid": "invalid",
            "worker_failed": "failed",
        }.get(source)
        if expected_status is not None and result.get("status") != expected_status:
            raise _Invalid("terminal worker status and portfolio pair differ")
        if source != "special_worker":
            launched = expected_status in {"exhausted", "cancelled", "failed"}
            _validate_worker_ledger_relation(
                portfolio,
                plan,
                physical,
                by_id,
                phase,
                result,
                launched=launched,
            )
            if launched and result.get("artifacts") != []:
                raise _Invalid("terminal worker retained ungoverned output")
        if phase == "producer":
            if attempt.evidence_sha256 is not None:
                raise _Invalid("noncompleted producer retained Evidence")
            _require_unstarted_checker(portfolio, by_id)
        else:
            evidence_parts = _attempt_evidence_semantics(portfolio, plan, physical, by_id)
            if evidence_parts[2] not in {"proved", "refuted"}:
                raise _Invalid("checker worker lacks produced Evidence")
            _validate_completed_worker(
                portfolio,
                plan,
                physical,
                by_id,
                "producer",
                retained_output=True,
            )
            if attempt.checker_decision_sha256 is not None:
                raise _Invalid("noncompleted checker retained a decision")
        return phase

    evidence_parts = _attempt_evidence_semantics(portfolio, plan, physical, by_id)
    (
        evidence_raw,
        evidence,
        evidence_status,
        strategy,
        checker,
        environment,
        certificate_formats,
    ) = evidence_parts
    if source == "evidence_invalid":
        if evidence_raw is not None or evidence is not None or evidence_status is not None:
            raise _Invalid("EVIDENCE_INVALID retained validated Evidence")
        _validate_completed_worker(
            portfolio,
            plan,
            physical,
            by_id,
            "producer",
            retained_output=False,
        )
        _require_unstarted_checker(portfolio, by_id)
        return "producer"

    if evidence_raw is None or evidence is None or evidence_status is None:
        raise _Invalid("semantic terminal pair lacks validated Evidence")
    expected_evidence_status = {
        "evidence_unsupported": "unsupported",
        "evidence_exhausted": "exhausted",
        "evidence_cancelled": "cancelled",
        "evidence_error": "error",
        "evidence_incomplete": "incomplete",
        "evidence_truncated": "truncated",
    }.get(source)
    if expected_evidence_status is not None:
        if evidence_status != expected_evidence_status:
            raise _Invalid("Evidence outcome and outer portfolio pair differ")
        _validate_completed_worker(
            portfolio,
            plan,
            physical,
            by_id,
            "producer",
            retained_output=True,
        )
        _require_unstarted_checker(portfolio, by_id)
        return "producer"
    if evidence_status not in {"proved", "refuted"}:
        raise _Invalid("checker path lacks produced Evidence")
    if source == "evidence_protocol_limit":
        try:
            too_long = len(evidence_raw.decode("ascii")) > MAX_WORKER_ARGUMENT_CODEPOINTS
        except UnicodeDecodeError as exc:
            raise _Invalid("Evidence protocol bytes are not ASCII") from exc
        if not too_long:
            raise _Invalid("EVIDENCE_PROTOCOL_LIMIT is below its exact limit")
        _validate_completed_worker(
            portfolio,
            plan,
            physical,
            by_id,
            "producer",
            retained_output=True,
        )
        _require_unstarted_checker(portfolio, by_id)
        return "producer"

    _validate_completed_worker(
        portfolio,
        plan,
        physical,
        by_id,
        "producer",
        retained_output=True,
    )
    if source == "certificate_invalid":
        if (
            attempt.checker_decision_sha256 is not None
            or f"checker_decision_{attempt.attempt_order:06d}" in by_id
            or f"checker_certificate_{attempt.attempt_order:06d}" in by_id
        ):
            raise _Invalid("invalid Certificate retained a checker decision")
        _validate_completed_worker(
            portfolio,
            plan,
            physical,
            by_id,
            "checker",
            retained_output=False,
        )
        return "checker"

    _validate_completed_worker(
        portfolio,
        plan,
        physical,
        by_id,
        "checker",
        retained_output=True,
    )
    verdict, decision = _attempt_checker_semantics(
        portfolio,
        physical,
        by_id,
        evidence_raw,
        evidence,
        evidence_status,
        strategy,
        checker,
        environment,
        certificate_formats,
    )
    valid = {
        "checked_proof": evidence_status == "proved"
        and verdict == "verified"
        and decision.agreement,
        "checked_refutation": evidence_status == "refuted"
        and verdict == "verified"
        and decision.agreement,
        "certificate_exhausted": verdict == "exhausted",
        "certificate_cancelled": verdict == "cancelled",
        "certificate_truncated": verdict == "truncated",
        "certificate_inconclusive": verdict in {"unsupported", "inconclusive"},
        "certificate_rejected": verdict == "invalid",
        "certificate_disagreed": verdict in {"verified", "disagreement"} and not decision.agreement,
        "certificate_failed": verdict == "verifier_failed",
    }.get(source, False)
    if not valid:
        raise _Invalid("Certificate verdict and outer portfolio pair differ")
    return "checker"


def _special_worker_outcome(
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    phase: str,
) -> str:
    attempt = portfolio.attempts[-1]
    result = _terminal_observation(portfolio, physical, by_id, phase)
    status = result.get("status")
    reason = result.get("reason_code")
    relevant_before, relevant_after = _terminal_worker_ledgers(portfolio, physical, by_id, phase)
    if not _terminal_transition_is_closed(portfolio, plan):
        raise _Invalid("special worker outcome is not the terminal transition")
    if reason == "LAUNCH_FAILED":
        if (
            status != "refused"
            or relevant_before != relevant_after
            or result.get("tree_terminated") is not False
            or result.get("lease_reconciled") is not False
            or result.get("artifacts") != []
            or (
                phase == "producer"
                and (
                    attempt.evidence_sha256 is not None
                    or attempt.checker_worker_result_sha256 is not None
                    or attempt.checker_status != "not_started"
                    or attempt.checker_decision_sha256 is not None
                )
            )
            or (
                phase == "checker"
                and (
                    attempt.producer_status != "completed"
                    or attempt.producer_reason_code != "COMPLETED"
                    or attempt.evidence_sha256 is None
                    or attempt.checker_decision_sha256 is not None
                )
            )
        ):
            raise _Invalid("LAUNCH_FAILED is not an exact nonlaunched refusal")
        return "launch_refused"
    if reason == "EXECUTABLE_INVALID":
        if (
            relevant_before != relevant_after
            or result.get("tree_terminated") is not False
            or result.get("lease_reconciled") is not False
            or result.get("artifacts") != []
            or (
                phase == "producer"
                and (
                    attempt.evidence_sha256 is not None
                    or attempt.checker_worker_result_sha256 is not None
                    or attempt.checker_decision_sha256 is not None
                )
            )
            or (
                phase == "checker"
                and (
                    attempt.producer_status != "completed"
                    or attempt.producer_reason_code != "COMPLETED"
                    or attempt.evidence_sha256 is None
                    or attempt.checker_decision_sha256 is not None
                )
            )
        ):
            raise _Invalid("EXECUTABLE_INVALID changed the parent ledger")
        if status == "refused":
            return "executable_refused"
        if status == "invalid":
            return "executable_invalid"
        raise _Invalid("EXECUTABLE_INVALID worker status is not governed")
    raise _Invalid("worker outcome does not require a discriminator")


def _exact_audit_relation(
    *,
    audit: RunAuditBundle,
    replay: RunAuditReplayResult,
    planning_request: bytes,
    route_result: bytes,
    planning_result: bytes,
    portfolio_request: bytes,
    anchored_parent_budget: bytes,
) -> tuple[
    dict[str, object],
    dict[str, object],
    ProofSearchPortfolioResult,
    dict[str, bytes],
    dict[str, dict[str, object]],
    bytes,
]:
    manifest, logical, portfolio, physical, by_id, final_budget = _portfolio_from_audit(audit)
    portfolio_raw = _record_bytes(physical, by_id, "portfolio_result")
    portfolio_request_raw = _record_bytes(physical, by_id, "portfolio_request")
    initial_budget_raw = _record_bytes(physical, by_id, "initial_parent_budget")
    provenance_raw = _record_bytes(physical, by_id, "execution_provenance")
    governed_pair = (portfolio.status, portfolio.reason_code)
    portfolio_request_identity = parse_proof_search_portfolio_request(
        portfolio_request
    ).request_sha256
    expected_portfolio_request_identity = (
        None
        if governed_pair == ("invalid", "PORTFOLIO_INPUT_INVALID")
        else portfolio_request_identity
    )
    expected_planning_identity = (
        None if governed_pair == ("invalid", "PORTFOLIO_INPUT_INVALID") else _sha(planning_result)
    )
    if (
        portfolio.reason_code not in _PORTFOLIO_PAIRS.get(portfolio.status, set())
        or replay.status != "complete"
        or replay.reason_code != "REPLAY_COMPLETE"
        or replay.manifest_sha256 != _sha(audit.manifest)
        or replay.bundle_sha256 != _sha(audit.manifest)
        or replay.logical_report_sha256 != _sha(audit.logical_report)
        or replay.execution_provenance_sha256 != manifest.get("execution_provenance_sha256")
        or replay.portfolio_status != portfolio.status
        or replay.mathematical_verdict != portfolio.mathematical_verdict
        or replay.authority_tier != portfolio.authority_tier
        or audit.logical_report != _record_bytes(physical, by_id, "logical_report")
        or manifest.get("planning_request_sha256") != _sha(planning_request)
        or manifest.get("route_result_sha256") != _sha(route_result)
        or manifest.get("planning_result_sha256") != _sha(planning_result)
        or manifest.get("portfolio_request_sha256") != _sha(portfolio_request)
        or manifest.get("portfolio_result_sha256") != _sha(portfolio_raw)
        or manifest.get("initial_parent_budget_sha256") != _sha(anchored_parent_budget)
        or manifest.get("final_parent_budget_sha256") != _sha(final_budget)
        or manifest.get("logical_report_sha256") != _sha(audit.logical_report)
        or portfolio_request_raw != portfolio_request
        or initial_budget_raw != anchored_parent_budget
        or _record_bytes(physical, by_id, "planning_request") != planning_request
        or _record_bytes(physical, by_id, "capability_route_result") != route_result
        or _record_bytes(physical, by_id, "planning_result") != planning_result
        or logical.get("planning_request_sha256") != _sha(planning_request)
        or logical.get("route_result_sha256") != _sha(route_result)
        or logical.get("planning_result_sha256") != _sha(planning_result)
        or logical.get("portfolio_request_sha256") != _sha(portfolio_request)
        or logical.get("status") != governed_pair[0]
        or logical.get("reason_code") != governed_pair[1]
        or logical.get("mathematical_verdict") != portfolio.mathematical_verdict
        or logical.get("authority_tier") != portfolio.authority_tier
        or logical.get("selected_strategy_sha256") != portfolio.selected_strategy_sha256
        or logical.get("selected_evidence_sha256") != portfolio.selected_evidence_sha256
        or logical.get("selected_certificate_sha256") != portfolio.selected_certificate_sha256
        or logical.get("selected_checker_decision_sha256")
        != portfolio.selected_checker_decision_sha256
        or portfolio.planning_result_sha256 != expected_planning_identity
        or portfolio.request_sha256 != expected_portfolio_request_identity
        or _sha(provenance_raw) not in physical
    ):
        raise _Invalid("audit graph differs from current execution inputs")
    return manifest, logical, portfolio, physical, by_id, final_budget


def _exact_internal_shape(
    portfolio: ProofSearchPortfolioResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    anchored_parent_budget: bytes,
) -> tuple[str, str]:
    pair = (portfolio.status, portfolio.reason_code)
    if pair == ("invalid", "PORTFOLIO_INPUT_INVALID"):
        if (
            portfolio.request_sha256 is not None
            or portfolio.planning_result_sha256 is not None
            or portfolio.initial_parent_budget_sha256 is not None
            or portfolio.final_parent_budget_sha256 is not None
            or portfolio.attempts
            or portfolio.inconclusive_outcomes
            or any(
                item is not None
                for item in (
                    portfolio.selected_strategy_sha256,
                    portfolio.selected_evidence_sha256,
                    portfolio.selected_certificate_sha256,
                    portfolio.selected_checker_decision_sha256,
                )
            )
            or portfolio.authority_tier != "none"
            or portfolio.mathematical_verdict != "none"
            or _record_bytes(physical, by_id, "initial_parent_budget") != anchored_parent_budget
            or _record_bytes(physical, by_id, "final_parent_budget") != anchored_parent_budget
            or any("worker_observation" in role_id for role_id in by_id)
        ):
            raise _Invalid("prelaunch-invalid portfolio shape differs")
        return "PORTFOLIO_INPUT_INVARIANT", "coordinator"
    if pair == ("invalid", "PORTFOLIO_EXECUTION_INVALID"):
        if (
            any(
                item is not None
                for item in (
                    portfolio.selected_strategy_sha256,
                    portfolio.selected_evidence_sha256,
                    portfolio.selected_certificate_sha256,
                    portfolio.selected_checker_decision_sha256,
                )
            )
            or portfolio.authority_tier != "none"
            or portfolio.mathematical_verdict != "none"
        ):
            raise _Invalid("execution-invalid portfolio selection differs")
        return "PORTFOLIO_EXECUTION_INVARIANT", "coordinator"
    invariant_codes = {
        "REQUEST_INVALID": "WORKER_REQUEST_INVARIANT",
        "PLAN_INVALID": "WORKER_PLAN_INVARIANT",
        "STRATEGY_MISMATCH": "WORKER_STRATEGY_INVARIANT",
        "BUDGET_INVALID": "WORKER_BUDGET_INVARIANT",
        "TREE_CLEANUP_FAILED": "CLEANUP_INVARIANT",
        "SUPERVISOR_FAILED": "SUPERVISOR_INVARIANT",
    }
    code = invariant_codes.get(portfolio.reason_code)
    if code is None:
        raise _Invalid("portfolio pair is not an invariant-owned row")
    phase = "cleanup" if code == "CLEANUP_INVARIANT" else "coordinator"
    terminal_phase = _terminal_phase(portfolio)
    observation = _terminal_observation(portfolio, physical, by_id, terminal_phase)
    if observation.get("reason_code") != portfolio.reason_code:
        raise _Invalid("invariant pair is not the final worker observation")
    return code, phase


def _classify_exact_portfolio(
    *,
    request: ExecutionDispositionRequest,
    portfolio: ProofSearchPortfolioResult,
    plan: PlanningResult,
    physical: dict[str, bytes],
    by_id: dict[str, dict[str, object]],
    anchored_parent_budget: bytes,
) -> tuple[str, str, str | None, tuple[str, ...], str | None]:
    status, reason = portfolio.status, portfolio.reason_code
    pair = (status, reason)
    if status == "invalid":
        code, phase = _exact_internal_shape(portfolio, physical, by_id, anchored_parent_budget)
        return "internal_error", phase, code, (), None

    phase = _validate_terminal_pair_relation(portfolio, plan, physical, by_id)
    if pair == ("succeeded", "CHECKED_PROOF"):
        return "checked_proof", "completed", None, (), None
    if pair == ("succeeded", "CHECKED_REFUTATION"):
        return "checked_refutation", "completed", None, (), None

    if reason in {
        "REQUEST_INVALID",
        "PLAN_INVALID",
        "STRATEGY_MISMATCH",
        "BUDGET_INVALID",
        "TREE_CLEANUP_FAILED",
        "SUPERVISOR_FAILED",
    }:
        code, phase = _exact_internal_shape(portfolio, physical, by_id, anchored_parent_budget)
        return "internal_error", phase, code, (), None
    result = _terminal_observation(portfolio, physical, by_id, phase)

    if reason == "CANCELLED":
        if (
            request.cancellation_intent is None
            or request.cancellation_armed is not True
            or result.get("status") != "cancelled"
            or result.get("reason_code") != "CANCELLED"
            or result.get("tree_terminated") is not True
            or result.get("lease_reconciled") is not True
            or not _terminal_transition_is_closed(portfolio, plan)
        ):
            raise _Invalid("CANCELLED lacks exact intent and worker evidence")
        return (
            f"{request.cancellation_intent.origin_source}_cancellation",
            phase,
            None,
            (),
            None,
        )

    if status == "exhausted" and reason in {
        "BUDGET_INSUFFICIENT",
        "WALL_TIME_EXHAUSTED",
        "CPU_TIME_EXHAUSTED",
        "MEMORY_EXHAUSTED",
        "OUTPUT_EXHAUSTED",
        "DIAGNOSTIC_EXHAUSTED",
    }:
        if result.get("reason_code") != reason:
            raise _Invalid("exhaustion is not the final worker observation")
        if reason == "BUDGET_INSUFFICIENT" and (
            result.get("status") != "refused"
            or result.get("tree_terminated") is not False
            or result.get("lease_reconciled") is not False
            or result.get("artifacts") != []
        ):
            raise _Invalid("BUDGET_INSUFFICIENT is not an exact pre-reservation refusal")
        static = {
            "WALL_TIME_EXHAUSTED": ("wall_time_us",),
            "CPU_TIME_EXHAUSTED": ("cpu_time_us",),
            "MEMORY_EXHAUSTED": ("memory_bytes",),
            "OUTPUT_EXHAUSTED": ("output_bytes",),
            "DIAGNOSTIC_EXHAUSTED": ("diagnostic_bytes",),
        }
        dimensions = (
            _budget_dimensions(portfolio, plan, physical, by_id, phase)
            if reason == "BUDGET_INSUFFICIENT"
            else static[reason]
        )
        return "budget_exhaustion", phase, None, dimensions, None

    if reason in {"LAUNCH_FAILED", "EXECUTABLE_INVALID"}:
        outcome_kind = _special_worker_outcome(portfolio, plan, physical, by_id, phase)
        if reason == "EXECUTABLE_INVALID" and outcome_kind == "executable_invalid":
            return (
                "internal_error",
                "coordinator",
                "WORKER_EXECUTABLE_INVARIANT",
                (),
                outcome_kind,
            )
        cause = (
            "producer_failure"
            if reason == "LAUNCH_FAILED" and phase == "producer"
            else "verifier_failure"
            if reason == "LAUNCH_FAILED"
            else "producer_refusal"
            if phase == "producer"
            else "verifier_refusal"
        )
        return cause, phase, None, (), outcome_kind

    if pair == ("inconclusive", "CHECKER_INCONCLUSIVE"):
        outcome_kind = _checker_outcome_kind(portfolio, physical, by_id)
        return (
            "verifier_refusal"
            if outcome_kind == "certificate_unsupported"
            else "inconclusive_execution",
            "checker",
            None,
            (),
            outcome_kind,
        )

    ordinary: dict[tuple[str, str], tuple[str, str]] = {
        ("ambiguous", "EVIDENCE_INCOMPLETE"): ("ambiguity", "producer"),
        ("unsupported", "ISOLATION_UNSUPPORTED"): ("unsupported_execution_environment", "producer"),
        ("inconclusive", "ISOLATION_UNSUPPORTED"): ("unsupported_execution_environment", "checker"),
        ("unsupported", "EVIDENCE_UNSUPPORTED"): ("producer_refusal", "producer"),
        ("exhausted", "EVIDENCE_EXHAUSTED"): ("producer_refusal", "producer"),
        ("cancelled", "EVIDENCE_CANCELLED"): ("producer_refusal", "producer"),
        ("exhausted", "CHECKER_EXHAUSTED"): ("verifier_refusal", "checker"),
        ("cancelled", "CHECKER_CANCELLED"): ("verifier_refusal", "checker"),
        ("truncated", "EVIDENCE_TRUNCATED"): ("truncation", "producer"),
        ("truncated", "CHECKER_TRUNCATED"): ("truncation", "checker"),
        ("disagreement", "CHECKER_REJECTED"): ("checker_disagreement", "checker"),
        ("disagreement", "CHECKER_DISAGREED"): ("checker_disagreement", "checker"),
        ("invalid_evidence", "EVIDENCE_INVALID"): ("invalid_evidence", "producer"),
        ("invalid_evidence", "EVIDENCE_PROTOCOL_LIMIT"): ("invalid_evidence", "producer"),
        ("invalid_evidence", "CERTIFICATE_INVALID"): ("invalid_evidence", "checker"),
        ("failed", "EXIT_FAILED"): ("producer_failure", "producer"),
        ("failed", "PROTOCOL_FAILED"): ("producer_failure", "producer"),
        ("failed", "EVIDENCE_ERROR"): ("producer_failure", "producer"),
        ("verifier_failed", "EXIT_FAILED"): ("verifier_failure", "checker"),
        ("verifier_failed", "PROTOCOL_FAILED"): ("verifier_failure", "checker"),
        ("verifier_failed", "CERTIFICATE_INVALID"): ("verifier_failure", "checker"),
    }
    classified = ordinary.get(pair)
    if classified is None or classified[1] != phase:
        raise _Invalid("portfolio pair has no exact governed classification")
    return classified[0], classified[1], None, (), None


def _complete_result(
    *,
    request_input: bytes,
    request: ExecutionDispositionRequest,
    anchored_parent_budget: bytes,
    portfolio_request: bytes,
    audit: RunAuditBundle,
    replay: RunAuditReplayResult,
    route: CapabilityRouteResult,
    plan: PlanningResult,
    portfolio: ProofSearchPortfolioResult,
    cause: str,
    phase: str,
    code: str | None,
    dimensions: tuple[str, ...],
    outcome_kind: str | None,
    portfolio_relation: str = "exact",
) -> ExecutionDispositionBundle:
    manifest, physical, by_id = _audit_inventory(audit)
    del manifest
    portfolio_raw = _record_bytes(physical, by_id, "portfolio_result")
    provenance_sha = replay.execution_provenance_sha256
    if provenance_sha is None:
        raise _Invalid("complete replay lacks provenance identity")
    selected = cause in {"checked_proof", "checked_refutation"}
    result = _new_result(
        request_input=request_input,
        request=request,
        cause=cause,
        phase=phase,
        code=code,
        resource_dimensions=dimensions,
        execution_state="replayed_complete",
        portfolio_relation=portfolio_relation,
        portfolio_outcome_kind=outcome_kind,
        base_parent_budget_sha256=request.base_parent_budget_sha256,
        anchored_parent_budget=anchored_parent_budget,
        planning_result_sha256=request.planning_result_sha256,
        portfolio_request=portfolio_request,
        audit=audit,
        replay=replay,
        logical_report_sha256=_sha(audit.logical_report),
        portfolio_result_sha256=_sha(portfolio_raw),
        execution_provenance_sha256=provenance_sha,
        route_status=route.status,
        route_reason_code=route.reason_code,
        planning_status=plan.status,
        planning_reason_code=plan.reason_code,
        portfolio_status=portfolio.status,
        portfolio_reason_code=portfolio.reason_code,
        selected_strategy_sha256=(portfolio.selected_strategy_sha256 if selected else None),
        selected_evidence_sha256=(portfolio.selected_evidence_sha256 if selected else None),
        selected_certificate_sha256=(portfolio.selected_certificate_sha256 if selected else None),
        selected_checker_decision_sha256=(
            portfolio.selected_checker_decision_sha256 if selected else None
        ),
        linked_authority_tier=portfolio.authority_tier if selected else "none",
    )
    return _new_bundle(result)


def execute_with_disposition(
    disposition_request: bytes,
    planning_request: bytes,
    route_result: bytes,
    planning_result: bytes,
    base_parent_budget: bytes | None,
    descriptors: tuple[bytes, ...],
    bindings: tuple[bytes, ...],
    artifacts: tuple[tuple[str, bytes], ...],
    executable_paths: tuple[tuple[str, str], ...],
    workspace_root: str | None,
    cancel_event: Event | None = None,
) -> ExecutionDispositionBundle:
    """Validate, execute once when planned, replay once, and classify closedly."""
    if (
        type(disposition_request) is not bytes
        or type(planning_request) is not bytes
        or type(route_result) is not bytes
        or type(planning_result) is not bytes
        or (base_parent_budget is not None and type(base_parent_budget) is not bytes)
        or type(descriptors) is not tuple
        or type(bindings) is not tuple
        or type(artifacts) is not tuple
        or type(executable_paths) is not tuple
        or (workspace_root is not None and type(workspace_root) is not str)
        or (cancel_event is not None and type(cancel_event) is not Event)
    ):
        _fail("type", "$", "coordinator inputs require exact built-in types")

    try:
        _validate_effect_string_ceilings(executable_paths, workspace_root)
        artifact_bytes = _validate_input_collections(
            (
                disposition_request,
                planning_request,
                route_result,
                planning_result,
                *((base_parent_budget,) if base_parent_budget is not None else ()),
            ),
            descriptors,
            bindings,
            artifacts,
        )
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except _Exhausted:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=None,
                cause="internal_error",
                phase="coordinator",
                code="COORDINATOR_LIMIT_EXHAUSTED",
            )
        )
    except Exception as exc:
        _fail("type", "$", str(exc))

    try:
        request = _request_from_mapping(_parse(disposition_request))
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except _Exhausted:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=None,
                cause="internal_error",
                phase="coordinator",
                code="COORDINATOR_LIMIT_EXHAUSTED",
            )
        )
    except Exception:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=None,
                cause="invalid_request",
                phase="request",
                code="REQUEST_INVALID",
            )
        )

    inventory_code = _request_inventory_relation(
        request,
        planning_request,
        route_result,
        planning_result,
        base_parent_budget,
        descriptors,
        bindings,
        artifacts,
    )
    if inventory_code is not None:
        retained = inventory_code in {"BINDING_INPUT_INVALID", "ARTIFACT_INPUT_INVALID"}
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request if retained else None,
                cause="invalid_request",
                phase="request",
                code=inventory_code,
            )
        )

    event_paired = request.cancellation_armed == (cancel_event is not None)
    if not event_paired:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="request",
                code="INTENT_EVENT_MISMATCH",
            )
        )

    try:
        planning = parse_planning_request(planning_request)
        supplied_route = parse_capability_route_result(route_result)
        fresh_route = route_capabilities(planning.route_request, descriptors, artifact_bytes)
        fresh_route_raw = capability_route_result_bytes(fresh_route)
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="routing",
                code="ROUTE_INPUT_INVALID",
            )
        )
    if fresh_route_raw != route_result or fresh_route != supplied_route:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="routing",
                code="ROUTE_INPUT_INVALID",
                route_status=("invalid" if supplied_route.status == "invalid" else None),
                route_reason_code=("INVALID_INPUT" if supplied_route.status == "invalid" else None),
            )
        )
    if fresh_route.status == "invalid":
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="routing",
                code="ROUTE_INPUT_INVALID",
                route_status="invalid",
                route_reason_code="INVALID_INPUT",
            )
        )

    try:
        supplied_plan = parse_planning_result(planning_result)
        fresh_plan = plan_strategies(planning_request, route_result, descriptors, artifact_bytes)
        fresh_plan_raw = planning_result_bytes(fresh_plan)
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="planning",
                code="PLANNING_INPUT_INVALID",
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status="invalid",
                planning_reason_code="INVALID_INPUT",
            )
        )
    if fresh_plan_raw != planning_result or fresh_plan != supplied_plan:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="planning",
                code="PLANNING_INPUT_INVALID",
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status="invalid",
                planning_reason_code="INVALID_INPUT",
            )
        )
    if fresh_plan.status == "invalid":
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="planning",
                code="PLANNING_INPUT_INVALID",
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status="invalid",
                planning_reason_code="INVALID_INPUT",
            )
        )

    if fresh_plan.status != "planned":
        if (
            base_parent_budget is not None
            or bindings
            or executable_paths
            or workspace_root is not None
            or cancel_event is not None
            or request.cancellation_armed
        ):
            code = (
                "INTENT_EVENT_MISMATCH"
                if request.cancellation_armed or cancel_event is not None
                else "REQUEST_INVALID"
            )
            return _new_bundle(
                _new_result(
                    request_input=disposition_request,
                    request=request if code != "REQUEST_INVALID" else None,
                    cause="invalid_request",
                    phase="request",
                    code=code,
                )
            )
        if fresh_plan.status == "ambiguous":
            cause, phase = "ambiguity", "routing"
        elif fresh_plan.status == "exhausted":
            phase = "routing" if fresh_route.status == "exhausted" else "planning"
            cause = "budget_exhaustion"
        elif fresh_plan.status == "unsupported":
            cause, phase = _unsupported_cause(fresh_route, planning_request, descriptors), "routing"
        else:
            raise AssertionError("fresh planner returned an unknown closed status")
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause=cause,
                phase=phase,
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status=fresh_plan.status,
                planning_reason_code=fresh_plan.reason_code,
            )
        )

    try:
        _execution_inputs_valid(fresh_plan, bindings, artifacts, executable_paths, workspace_root)
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except ProofSearchPortfolioValidationError as exc:
        code = (
            "BINDING_INPUT_INVALID"
            if exc.kind == "binding"
            else "ARTIFACT_INPUT_INVALID"
            if exc.kind == "artifact"
            else "EXECUTION_INPUT_INVALID"
        )
        phase = "planning" if code != "EXECUTION_INPUT_INVALID" else "coordinator"
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase=phase,
                code=code,
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status=fresh_plan.status,
                planning_reason_code=fresh_plan.reason_code,
            )
        )
    except Exception:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="coordinator",
                code="EXECUTION_INPUT_INVALID",
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status=fresh_plan.status,
                planning_reason_code=fresh_plan.reason_code,
            )
        )
    if base_parent_budget is None:
        return _new_bundle(
            _new_result(
                request_input=disposition_request,
                request=request,
                cause="invalid_request",
                phase="coordinator",
                code="EXECUTION_INPUT_INVALID",
                planning_result_sha256=request.planning_result_sha256,
                route_status=fresh_route.status,
                route_reason_code=fresh_route.reason_code,
                planning_status=fresh_plan.status,
                planning_reason_code=fresh_plan.reason_code,
            )
        )

    common = {
        "request_input": disposition_request,
        "request": request,
        "base_parent_budget_sha256": request.base_parent_budget_sha256,
        "planning_result_sha256": request.planning_result_sha256,
        "route_status": fresh_route.status,
        "route_reason_code": fresh_route.reason_code,
        "planning_status": fresh_plan.status,
        "planning_reason_code": fresh_plan.reason_code,
    }
    try:
        anchored = _derive_anchor(base_parent_budget, request.request_sha256)
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except _AnchorCollision:
        return _new_bundle(
            _new_result(
                **common,
                cause="invalid_request",
                phase="coordinator",
                code="RESERVED_EXTENSION_COLLISION",
            )
        )
    except Exception:
        return _new_bundle(
            _new_result(
                **common,
                cause="internal_error",
                phase="coordinator",
                code="BUDGET_ANCHOR_INVALID",
            )
        )

    try:
        portfolio_request = make_proof_search_portfolio_request(
            planning_result=planning_result,
            parent_budget=anchored,
            descriptors=descriptors,
            bindings=bindings,
            artifacts=artifacts,
        )
        _prepare_portfolio(
            portfolio_request,
            planning_result,
            anchored,
            descriptors,
            bindings,
            artifact_bytes,
            executable_paths,
            workspace_root,
            cancel_event,
        )
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception:
        return _new_bundle(
            _new_result(
                **common,
                cause="internal_error",
                phase="coordinator",
                code="PORTFOLIO_REQUEST_INVALID",
                anchored_parent_budget=anchored,
            )
        )

    ready = {
        **common,
        "anchored_parent_budget": anchored,
        "portfolio_request": portfolio_request,
    }
    try:
        audit = _shallow_audit_bundle(
            execute_audited_run(
                planning_request,
                route_result,
                portfolio_request,
                planning_result,
                anchored,
                descriptors,
                bindings,
                artifact_bytes,
                executable_paths,
                workspace_root,
                cancel_event,
            )
        )
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception:
        return _new_bundle(
            _new_result(
                **ready,
                cause="internal_error",
                phase="audit",
                code="AUDITED_EXECUTION_INVALID",
                execution_state="attempted_no_bundle",
            )
        )

    try:
        replay = _shallow_replay(replay_run_audit(audit.manifest, audit.objects), audit)
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception:
        return _new_bundle(
            _new_result(
                **ready,
                cause="internal_error",
                phase="audit",
                code="AUDITED_EXECUTION_INVALID",
                execution_state="attempted_no_bundle",
            )
        )
    if replay.status != "complete":
        replay_failure = (
            _sha(audit.manifest),
            replay.replay_result_sha256,
            replay.status,
            replay.reason_code,
        )
        del audit, replay
        return _new_bundle(
            _new_result(
                **ready,
                cause="internal_error",
                phase="replay",
                code=(
                    "AUDIT_REPLAY_EXHAUSTED"
                    if replay_failure[2] == "exhausted"
                    else "AUDIT_REPLAY_INVALID"
                ),
                execution_state="bundle_replay_failed",
                replay_failure=replay_failure,
            )
        )

    try:
        (
            _manifest,
            _logical,
            portfolio,
            physical,
            by_id,
            _final_budget,
        ) = _exact_audit_relation(
            audit=audit,
            replay=replay,
            planning_request=planning_request,
            route_result=route_result,
            planning_result=planning_result,
            portfolio_request=portfolio_request,
            anchored_parent_budget=anchored,
        )
        cause, phase, code, dimensions, outcome_kind = _classify_exact_portfolio(
            request=request,
            portfolio=portfolio,
            plan=fresh_plan,
            physical=physical,
            by_id=by_id,
            anchored_parent_budget=anchored,
        )
        return _complete_result(
            request_input=disposition_request,
            request=request,
            anchored_parent_budget=anchored,
            portfolio_request=portfolio_request,
            audit=audit,
            replay=replay,
            route=fresh_route,
            plan=fresh_plan,
            portfolio=portfolio,
            cause=cause,
            phase=phase,
            code=code,
            dimensions=dimensions,
            outcome_kind=outcome_kind,
        )
    except (MemoryError, KeyboardInterrupt, SystemExit):
        raise
    except Exception:
        try:
            _manifest, _logical, portfolio, _physical, _by_id, _final = _portfolio_from_audit(audit)
            return _complete_result(
                request_input=disposition_request,
                request=request,
                anchored_parent_budget=anchored,
                portfolio_request=portfolio_request,
                audit=audit,
                replay=replay,
                route=fresh_route,
                plan=fresh_plan,
                portfolio=portfolio,
                cause="internal_error",
                phase="audit",
                code="AUDIT_RELATION_INVALID",
                dimensions=(),
                outcome_kind=None,
                portfolio_relation="invalid",
            )
        except (MemoryError, KeyboardInterrupt, SystemExit):
            raise
        except Exception:
            return _new_bundle(
                _new_result(
                    **ready,
                    cause="internal_error",
                    phase="audit",
                    code="AUDITED_EXECUTION_INVALID",
                    execution_state="attempted_no_bundle",
                )
            )



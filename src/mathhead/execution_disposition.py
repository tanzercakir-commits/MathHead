def _classification_from_mapping(
    value: object, path: str = "$"
) -> ExecutionDispositionClassification:
    expected = {
        "schema",
        "disposition",
        "cause",
        "precedence_row",
        "precedence_rank",
        "phase",
        "origin_source",
        "observer_source",
        "observer_cancellation_id",
        "observer_basis",
        "resource_dimensions",
        "classification_sha256",
        "mathematical_authority",
    }
    item = _keys(value, expected, path)
    if item["schema"] != CLASSIFICATION_SCHEMA or item["mathematical_authority"] is not False:
        raise _Invalid(f"{path} classification constants differ")
    raw_dimensions = item["resource_dimensions"]
    if type(raw_dimensions) is not list or len(raw_dimensions) > len(RESOURCE_DIMENSIONS):
        raise _Invalid(f"{path}.resource_dimensions is not bounded")
    dimensions = tuple(
        _choice(raw, set(RESOURCE_DIMENSIONS), f"{path}.resource_dimensions[{index}]")
        for index, raw in enumerate(raw_dimensions)
    )
    if dimensions != tuple(sorted(set(dimensions))):
        raise _Invalid(f"{path}.resource_dimensions order or uniqueness differs")
    cause = _choice(item["cause"], _CAUSES, f"{path}.cause")
    disposition = _choice(item["disposition"], _DISPOSITIONS, f"{path}.disposition")
    phase = _choice(item["phase"], _PHASES, f"{path}.phase")
    rank = _quantity(item["precedence_rank"], f"{path}.precedence_rank", 90)
    row = item["precedence_row"]
    matched = any(
        cause in causes
        and disposition == expected_disposition
        and row == expected_row
        and rank == expected_rank
        and phase in phases
        and minimum <= len(dimensions) <= maximum
        for causes, expected_disposition, expected_row, expected_rank, phases, minimum, maximum in _CLASSIFICATION_ROWS
    )
    if not matched:
        raise _Invalid(f"{path} cause/disposition/precedence/phase relation differs")
    cancellation = cause in _ORIGIN_BY_CAUSE
    expected_origin = _ORIGIN_BY_CAUSE.get(cause)
    if cancellation:
        if (
            item["origin_source"] != expected_origin
            or item["observer_source"] != "supervisor"
            or item["observer_cancellation_id"] is not None
            or item["observer_basis"] != "replayed_worker_status_plus_accepted_contract"
        ):
            raise _Invalid(f"{path} cancellation observer relation differs")
    elif any(
        item[name] is not None
        for name in (
            "origin_source",
            "observer_source",
            "observer_cancellation_id",
            "observer_basis",
        )
    ):
        raise _Invalid(f"{path} non-cancellation observer fields must be null")
    result = _make(
        ExecutionDispositionClassification,
        schema=CLASSIFICATION_SCHEMA,
        disposition=disposition,
        cause=cause,
        precedence_row=row,
        precedence_rank=rank,
        phase=phase,
        origin_source=expected_origin if cancellation else None,
        observer_source="supervisor" if cancellation else None,
        observer_cancellation_id=None,
        observer_basis="replayed_worker_status_plus_accepted_contract" if cancellation else None,
        resource_dimensions=dimensions,
        classification_sha256=_digest(
            item["classification_sha256"], f"{path}.classification_sha256"
        ),
        mathematical_authority=False,
    )
    if result.classification_sha256 != _self_hash(
        _classification_mapping(result), "classification_sha256"
    ):
        raise _Invalid(f"{path}.classification_sha256 identity mismatch")
    return result


